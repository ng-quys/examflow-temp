// Helper functions for easy querying
export const getCourseById = (courseId: string): Course | undefined => {
  return INITIAL_COURSES.find((c) => c.id === courseId);
};

export const getChaptersByCourseId = (courseId: string, chapters: CourseChapter[] = INITIAL_CHAPTERS): CourseChapter[] => {
  return chapters.filter((ch) => ch.courseId === courseId);
};

export const getCLOsByCourseId = (courseId: string, clos: CourseCLO[] = INITIAL_CLOS): CourseCLO[] => {
  return clos.filter((clo) => clo.courseId === courseId);
};

export const getQuestionsByFilter = (
  questions: QuestionItem[],
  filters: {
    courseId?: string;
    chapterId?: string;
    topicId?: string;
    cloId?: string;
    bloom?: Bloom3Level | 'all';
    status?: 'approved' | 'pending' | 'rejected' | 'all';
    searchTerm?: string;
  }
): QuestionItem[] => {
  return questions.filter((q) => {
    if (filters.courseId && q.courseId !== filters.courseId) return false;
    if (filters.chapterId && q.chapterId !== filters.chapterId) return false;
    if (filters.topicId && q.topicId !== filters.topicId) return false;
    if (filters.cloId && q.cloId !== filters.cloId) return false;
    if (filters.bloom && filters.bloom !== 'all' && q.bloom !== filters.bloom) return false;
    if (filters.status && filters.status !== 'all' && q.status !== filters.status) return false;

    if (filters.searchTerm && filters.searchTerm.trim() !== '') {
      const term = filters.searchTerm.toLowerCase();
      const matchContent = q.content.toLowerCase().includes(term);
      const matchOptions = q.options.some((opt) => opt.toLowerCase().includes(term));
      const matchExplanation = q.explanation ? q.explanation.toLowerCase().includes(term) : false;
      if (!matchContent && !matchOptions && !matchExplanation) return false;
    }

    return true;
  });
};
